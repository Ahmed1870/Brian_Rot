#!/usr/bin/env python3
"""usage: sync.py <voice.mp3> <lesson.json> > src/sync.ts
Scene boundaries = pauses in the voice nearest to the char-weighted estimate.
Cues = char position of a phrase, interpolated across sentences snapped to local RMS dips."""
import sys,json,re,subprocess,wave,tempfile,os,numpy as np
mp3,js=sys.argv[1:3];L=json.load(open(js));fps=L["fps"]
wav=os.path.join(tempfile.gettempdir(),"sync16k.wav")
subprocess.run(["ffmpeg","-v","error","-y","-i",mp3,"-ac","1","-ar","16000",wav],check=True)
w=wave.open(wav);x=np.frombuffer(w.readframes(w.getnframes()),dtype=np.int16).astype(float)/32768
n=160;r=np.sqrt(np.convolve(x**2,np.ones(n)/n,"same"))[::n];r=np.convolve(r,np.ones(3)/3,"same");rs=r/r.max()
total=len(x)/16000;nz=np.where(rs>0.02)[0];t0,t1=nz[0]/100,nz[-1]/100
sil=[];i=0;s=rs<0.02
while i<len(s):
    if s[i]:
        j=i
        while j<len(s) and s[j]:j+=1
        if j-i>=45 and i>50 and j<len(s)-50:sil.append((i+j)/200)
        i=j
    else:i+=1
ch=lambda t:len(re.sub(r"\s","",t))
tx=[sc["text"] for sc in L["scenes"]];tot=sum(map(ch,tx));cum=0;b=[0.0]
for k in range(len(tx)-1):
    cum+=ch(tx[k]);est=t0+cum/tot*(t1-t0);b.append(min(sil,key=lambda a:abs(a-est)))
b.append(total)
def dip(t,lo,rad=1.2):
    a,c=int(max(t-rad,lo+0.6)*100),int((t+rad)*100);c=max(c,a+5);seg=rs[a:c];return (a+int(np.argmin(seg)))/100
out={"SC":[],"CUE":{},"SENT":{}}
for k,sc in enumerate(L["scenes"]):
    a=t0 if k==0 else b[k]+0.4;e=t1 if k==len(tx)-1 else b[k+1]-0.4
    t=sc["text"];sents=[m for m in re.finditer(r"[^!؟]+[!؟]?",t) if m.group().strip()]
    cl=[ch(m.group()) for m in sents];cs=np.cumsum([0]+cl)/sum(cl)
    sb=[a]
    for i in range(1,len(sents)):sb.append(dip(a+cs[i]*(e-a),sb[-1]))
    sb.append(e)
    out["SENT"][sc["id"]]=[round(v,2) for v in sb]
    for name,ph in sc["cues"].items():
        p=t.index(ph);si=max(i for i,m in enumerate(sents) if m.start()<=p)
        pre=ch(t[sents[si].start():p]);f=pre/max(cl[si],1)
        out["CUE"][sc["id"]+"_"+name]=round(sb[si]+f*(sb[si+1]-sb[si]),2)
bf=[round(v*fps) for v in b]
out["SC"]=[[bf[k],bf[k+1]] for k in range(len(tx))]
out["SC"][-1][1]=round(round(total)*fps)
print("// GENERATED by tools/sync.py from the voiceover. Do not edit by hand.")
print("export const SC: [number, number][] = %s;"%json.dumps(out["SC"]))
print("export const CUE: Record<string, number> = %s;"%json.dumps(out["CUE"],indent=1))
print("export const SENT: Record<string, number[]> = %s;"%json.dumps(out["SENT"]))
