import React from "react";
import { AbsoluteFill, Audio, Sequence, staticFile, useCurrentFrame } from "remotion";
import { Background, Shell, TopBar } from "./components/common";
import { Scene1 } from "./scenes/Scene1";
import { Scene2 } from "./scenes/Scene2";
import { Scene3 } from "./scenes/Scene3";
import { Scene4 } from "./scenes/Scene4";
import { Scene5 } from "./scenes/Scene5";
import { Scene6 } from "./scenes/Scene6";
import { FPS, TimeCtx, prog } from "./lib";
import { SFX } from "./sfx";

export const Lesson: React.FC = () => {
  const frame = useCurrentFrame();
  const t = frame / FPS;
  const black = prog(t, 239.2, 239.95);
  return (
    <TimeCtx.Provider value={t}>
      <AbsoluteFill style={{ background: "#0F172A" }}>
        <Background />
        <TopBar />
        <Shell idx={0}><Scene1 /></Shell>
        <Shell idx={1}><Scene2 /></Shell>
        <Shell idx={2}><Scene3 /></Shell>
        <Shell idx={3}><Scene4 /></Shell>
        <Shell idx={4}><Scene5 /></Shell>
        <Shell idx={5}><Scene6 /></Shell>
        {black > 0 && <AbsoluteFill style={{ background: "#000", opacity: black }} />}

        {/* voice-over */}
        <Audio src={staticFile("voiceover.mp3")} volume={1} />

        {/* sound design (generated by scripts/generate-audio.cjs) */}
        <Audio src={staticFile("sfx/ambient.wav")} loop volume={(f) => 0.07 * (1 - prog(f / FPS, 214.6, 216.6))} />
        <Sequence from={Math.round(216.7 * FPS)} layout="none">
          <Audio src={staticFile("sfx/outro.wav")} volume={(f) => 0.17 * prog(f / FPS, 0, 1.6) * (1 - prog(f / FPS, 21.6, 23.2))} />
        </Sequence>
        {SFX.map((s, i) => (
          <Sequence key={i} from={Math.round(s.at * FPS)} durationInFrames={Math.max(1, Math.round((s.dur ?? 3) * FPS))} layout="none">
            <Audio src={staticFile(`sfx/${s.file}.wav`)} volume={s.vol} />
          </Sequence>
        ))}
      </AbsoluteFill>
    </TimeCtx.Provider>
  );
};
