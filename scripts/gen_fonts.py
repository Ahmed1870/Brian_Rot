# Regenerates src/fonts/fontData.ts from the DejaVu TTFs (kept out of the repo to save space).
import base64
base='/usr/share/fonts/truetype/dejavu/'
names={'SANS_REG':'DejaVuSans.ttf','SANS_BOLD':'DejaVuSans-Bold.ttf','MONO_REG':'DejaVuSansMono.ttf','MONO_BOLD':'DejaVuSansMono-Bold.ttf'}
out="// GENERATED by scripts/gen_fonts.py\n"
for k,f in names.items(): out+=f"export const {k} = 'data:font/ttf;base64,{base64.b64encode(open(base+f,'rb').read()).decode()}';\n"
open('src/fonts/fontData.ts','w').write(out)
